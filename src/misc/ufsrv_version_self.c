#include "ufsrv_version_self.h"

#include <uflib/buffer_descriptor/buffer_descriptor.h>
#include "version.h"

#include <stdlib.h>

/* The binary's name; both servers define this from their CMake target. */
#ifndef APP_NAME_INJECTED
  #define APP_NAME_INJECTED "ufsrv"
#endif

static BufferDescriptor *
sLiveBuffer(BufferDescriptor *buffer_provided)
{
  if (buffer_provided)	return buffer_provided;

  buffer_provided = calloc(1, sizeof(BufferDescriptor));
  if (!buffer_provided)	return NULL;

  BufferDescriptorInit(buffer_provided, 192);
  if (!buffer_provided->data) {
    free(buffer_provided);
    return NULL;
  }

  return buffer_provided;
}

BufferDescriptor *
UfsrvSelfVersionDescribe(BufferDescriptor *buffer_provided)
{
  BufferDescriptor *out = sLiveBuffer(buffer_provided);

  if (!out)	return NULL;

  /* Generated by src/version.c.sh: the running binary's own version.c. */
  BufferDescriptorAppendFormatted(out, "{\"name\":\"%s\",\"version\":\"%s\",\"compiled\":\"%s\",\"by\":\"%s\"}",
      APP_NAME_INJECTED, UfsrvVersion(), UfsrvCompiledTimestamp(), UfsrvCompiledBy());

  return out;
}

BufferDescriptor *
UfsrvConsoleVersionSelfOnGet(ScriptHandlerContext *ctx)
{
	BufferDescriptor *buffer_provided = ctx->buffer;
  return UfsrvSelfVersionDescribe(buffer_provided);
}
